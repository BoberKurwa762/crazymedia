#!/usr/bin/env python3
"""Swap the background song.

    python3 tools/make_song.py path/to/your_song.mp3

Re-encodes it to 128 kbps (keeps the page small), saves it as assets/on_a_mission.mp3
and rewrites js/song-data.js. Needs ffmpeg; without it the file is embedded as-is.
The site finds the tempo and beat positions by itself when it loads, so nothing else to edit.
"""
import base64, os, shutil, subprocess, sys

if len(sys.argv) != 2:
    sys.exit(__doc__)
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = os.path.join(root, "assets", "on_a_mission.mp3")
if shutil.which("ffmpeg"):
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", sys.argv[1], "-map", "0:a",
                    "-map_metadata", "-1", "-c:a", "libmp3lame", "-b:a", "128k", "-write_xing", "1", out], check=True)
else:
    shutil.copy(sys.argv[1], out)
b64 = base64.b64encode(open(out, "rb").read()).decode()
with open(os.path.join(root, "js", "song-data.js"), "w") as f:
    f.write('/* Generated by tools/make_song.py */\nconst SONG_B64="' + b64 + '";\n')
print("done:", round(os.path.getsize(out) / 1e6, 2), "MB")
